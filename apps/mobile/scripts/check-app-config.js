#!/usr/bin/env node
// Fails (exit 1) when the Expo app config points at files that don't exist or are the wrong kind,
// or when the site address in config.ts is malformed. Runs as `npm test` in apps/mobile and in CI.
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const errors = [];
const warnings = [];

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  } catch (e) {
    errors.push(`${file}: could not be read as JSON (${e.message})`);
    return null;
  }
}

// Width/height from a PNG header, or null if the file isn't a PNG.
function pngSize(file) {
  const buf = fs.readFileSync(file);
  const sig = '89504e470d0a1a0a';
  if (buf.length < 24 || buf.subarray(0, 8).toString('hex') !== sig) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

// Every "./something.png" string in app.json, with the JSON path it came from.
function assetRefs(node, trail = []) {
  if (typeof node === 'string') return /^\.\.?\//.test(node) ? [{ at: trail.join('.'), file: node }] : [];
  if (node && typeof node === 'object') {
    return Object.entries(node).flatMap(([k, v]) => assetRefs(v, [...trail, k]));
  }
  return [];
}

// Expected minimum sizes for well-known Expo image fields.
const EXPECT = {
  'expo.icon': { square: true, min: 1024 },
  'expo.android.adaptiveIcon.foregroundImage': { square: true, min: 1024 },
  'expo.splash.image': { min: 512 },
  'expo.web.favicon': { square: true, min: 48 },
};

const app = readJson('app.json');
if (app) {
  for (const { at, file } of assetRefs(app)) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) {
      errors.push(`app.json ${at}: "${file}" does not exist`);
      continue;
    }
    if (!/\.png$/i.test(file)) continue;
    const size = pngSize(full);
    if (!size) {
      errors.push(`app.json ${at}: "${file}" is not a valid PNG`);
      continue;
    }
    const rule = EXPECT[at];
    if (rule) {
      if (rule.square && size.width !== size.height) errors.push(`app.json ${at}: "${file}" must be square (is ${size.width}x${size.height})`);
      if (Math.min(size.width, size.height) < rule.min) errors.push(`app.json ${at}: "${file}" must be at least ${rule.min}px (is ${size.width}x${size.height})`);
    }
  }
  if (!app.expo || !app.expo.android || !app.expo.android.package) errors.push('app.json: expo.android.package is missing');
}

// Native folders are generated by `expo prebuild`; a committed copy gets wiped on every prebuild.
for (const dir of ['android', 'ios']) {
  const tracked = path.join(root, dir);
  if (fs.existsSync(tracked) && fs.existsSync(path.join(root, '..', '..', '.git'))) {
    const ignore = fs.readFileSync(path.join(root, '..', '..', '.gitignore'), 'utf8');
    if (!ignore.includes(`apps/mobile/${dir}/`)) errors.push(`apps/mobile/${dir}/ exists but is not git-ignored; it is generated by "expo prebuild"`);
  }
}

// Site address the app opens.
const configTs = fs.readFileSync(path.join(root, 'config.ts'), 'utf8');
const m = configTs.match(/export const APP_URL\s*=\s*['"]([^'"]*)['"]/);
if (!m) {
  errors.push('config.ts: could not find `export const APP_URL = \'...\'`');
} else if (!m[1]) {
  warnings.push('config.ts: APP_URL is empty; the app will show its "Almost ready" screen');
} else if (!/^https:\/\/[^\s/]+(\/[^\s]*)?$/.test(m[1])) {
  errors.push(`config.ts: APP_URL "${m[1]}" must be an https:// address`);
}

// Native modules the code imports must be declared dependencies.
const pkg = readJson('package.json');
if (pkg) {
  const deps = { ...pkg.dependencies };
  const source = ['App.tsx', 'config.ts'].map((f) => fs.readFileSync(path.join(root, f), 'utf8')).join('\n');
  const imported = [...source.matchAll(/from\s+['"]([^'".][^'"]*)['"]/g)].map((x) => x[1].split('/').slice(0, x[1].startsWith('@') ? 2 : 1).join('/'));
  for (const name of new Set(imported)) {
    if (!deps[name]) errors.push(`package.json: "${name}" is imported but not listed in dependencies`);
  }
}

warnings.forEach((w) => console.warn(`warning: ${w}`));
if (errors.length) {
  errors.forEach((e) => console.error(`error: ${e}`));
  console.error(`\n${errors.length} problem(s) found in apps/mobile.`);
  process.exit(1);
}
console.log('apps/mobile: app config, assets and dependencies look good.');
