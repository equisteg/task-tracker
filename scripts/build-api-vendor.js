#!/usr/bin/env node
// Rebuilds api/_lib/vendor.js: a single self-contained bundle of the server's third-party libraries.
// The API ships its dependencies pre-bundled so Vercel never has to run npm install on this
// monorepo (whose workspace packages are not published and break installs on the build machines).
//
// Usage: node scripts/build-api-vendor.js     (requires network access to the npm registry)
'use strict';

const { execSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const VERSIONS = { pg: '8.23.0', nodemailer: '10.0.10', esbuild: '0.25.10' };
const out = path.resolve(__dirname, '..', 'api', '_lib', 'vendor.js');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'api-vendor-'));

try {
  fs.writeFileSync(path.join(work, 'package.json'), JSON.stringify({ private: true }));
  fs.writeFileSync(path.join(work, 'entry.js'), "module.exports = { pg: require('pg'), nodemailer: require('nodemailer') };\n");
  const pkgs = Object.entries(VERSIONS).map(([n, v]) => `${n}@${v}`).join(' ');
  execSync(`npm install --no-audit --no-fund --no-save ${pkgs}`, { cwd: work, stdio: 'inherit' });
  execSync(
    [
      'npx esbuild entry.js --bundle --platform=node --target=node18 --format=cjs',
      '--external:pg-native --external:cloudflare:sockets --legal-comments=eof',
      `--banner:js="/* Generated by scripts/build-api-vendor.js (pg@${VERSIONS.pg}, nodemailer@${VERSIONS.nodemailer}). Do not edit. */"`,
      `--outfile="${out}"`,
    ].join(' '),
    { cwd: work, stdio: 'inherit' }
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)}`);
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}
